/** phrase → translation for each supported language (English maps to itself). */
export const PHRASEBOOK: Record<Exclude<LanguageCode, 'en'>, PhraseTable> = {
  pid: PIDGIN,
  yo: YORUBA,
};

/**
 * Offline translation of a known interface string.
 * Returns null when the string is not in the phrasebook (the caller then asks
 * the AI translation route, or leaves the English text in place).
 */
export function translatePhrase(lang: LanguageCode, text: string): string | null {
  if (lang === 'en') return text;
  const table = PHRASEBOOK[lang];
  if (!table) return null;
  const key = text.trim();
  return table[key] ?? null;
}

/** All English phrases covered by the phrasebook (used for cache pre-seeding). */
export function phrasebookKeys(): string[] {
  return Object.keys(PIDGIN);
}
